import { describe, it, expect } from "vitest";
import { id3CommentFrame } from "@/lib/id3";

describe("id3CommentFrame", () => {
  it("starts with the ID3 magic bytes", () => {
    const frame = id3CommentFrame("AI-generated voice");
    const header = new TextDecoder().decode(frame.slice(0, 3));
    expect(header).toBe("ID3");
  });

  it("carries the comment text in the frame bytes", () => {
    const frame = id3CommentFrame("AI-generated voice disclosure");
    const text = new TextDecoder("utf-8", { fatal: false }).decode(frame);
    expect(text).toContain("AI-generated voice disclosure");
    expect(text).toContain("COMM");
  });

  it("declares ID3v2.3 in the tag header", () => {
    const frame = id3CommentFrame("x");
    expect(frame[3]).toBe(0x03); // major version
    expect(frame[4]).toBe(0x00); // revision
  });

  // Issue 14: the frame size field must be a plain 32-bit big-endian
  // integer to match the declared ID3v2.3 version, not a synchsafe
  // (4x7-bit) integer, which is only correct for ID3v2.4. The two
  // encodings agree as long as only the lowest byte of the size is
  // nonzero, so this needs a comment long enough that the frame body
  // crosses 256 bytes (a second byte becomes nonzero) for the mismatch
  // between "multiply by 256" (plain) and "multiply by 128" (synchsafe)
  // to actually produce different decoded values.
  it("encodes the frame size as a plain 32-bit big-endian integer, not synchsafe", () => {
    const longComment = "x".repeat(300);
    const frame = id3CommentFrame(longComment);

    // Layout: "ID3"(3) + version(2) + flags(1) + tag-size(4) = 10 byte tag
    // header, then "COMM"(4) + frame-size(4) + frame-flags(2) = 10 byte
    // frame header, so the frame size field is bytes [14, 18).
    const frameSizeBytes = frame.slice(14, 18);
    const plainBE =
      (frameSizeBytes[0] << 24) | (frameSizeBytes[1] << 16) | (frameSizeBytes[2] << 8) | frameSizeBytes[3];

    // frameBody = textEncoding(1) + lang(3) + shortDescription(1) + comment(300)
    const expectedFrameBodyLength = 1 + 3 + 1 + longComment.length;
    expect(plainBE).toBe(expectedFrameBodyLength);

    // Demonstrate the bug this guards against: interpreting the same
    // bytes as synchsafe (4x7-bit) would NOT recover the real length,
    // since 205 does not fit cleanly as a single 7-bit group the way the
    // old, buggy encoding assumed.
    const misreadAsSynchsafe =
      (frameSizeBytes[0] << 21) | (frameSizeBytes[1] << 14) | (frameSizeBytes[2] << 7) | frameSizeBytes[3];
    expect(misreadAsSynchsafe).not.toBe(expectedFrameBodyLength);

    // The overall tag size, in contrast, IS synchsafe in every ID3v2
    // version, including 2.3: decoding bytes [6, 10) as synchsafe must
    // recover the real frame length.
    const tagSizeBytes = frame.slice(6, 10);
    const tagSize =
      (tagSizeBytes[0] << 21) | (tagSizeBytes[1] << 14) | (tagSizeBytes[2] << 7) | tagSizeBytes[3];
    const frameLength = frame.length - 10; // minus the tag header itself
    expect(tagSize).toBe(frameLength);
  });

  it("round-trips a long comment without corrupting the tag", () => {
    const longComment = "This audio was generated by an AI voice clone. ".repeat(10);
    const frame = id3CommentFrame(longComment);
    const text = new TextDecoder("utf-8", { fatal: false }).decode(frame);
    expect(text).toContain(longComment);
  });
});
